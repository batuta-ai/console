let lang: Lang = "en";

export function parseLang(raw?: string | null): Lang {
  if (raw && raw.toLowerCase().startsWith("pt")) return "pt";
  return "en";
}

export function setLang(next: Lang) {
  lang = next;
  if (typeof document !== "undefined") {
    document.documentElement.lang = next === "pt" ? "pt-BR" : "en";
  }
}

export function currentLang(): Lang {
  return lang;
}

export function localeTag(): string {
  return lang === "pt" ? "pt-BR" : "en";
}

export function T(key: Msg, vars?: Record<string, string | number>): string {
  const pack = lang === "pt" ? pt : en;
  let s = pack[key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export async function bootLang(token: string) {
  try {
    const res = await fetch("/v0/capabilities", { headers: { Authorization: `Bearer ${token}` } });
    if (!res.ok) return;
    const caps = (await res.json()) as { lang?: string };
    setLang(parseLang(caps.lang));
  } catch {
    /* keep English default, same as the TUI */
  }
}

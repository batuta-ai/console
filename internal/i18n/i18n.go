func Lang() string {
	if v := os.Getenv("BATUTA_LANG"); v != "" {
		if strings.HasPrefix(strings.ToLower(v), "pt") {
			return "pt"
		}
		return "en"
	}
	for _, k := range []string{"LC_ALL", "LANG"} {
		if strings.HasPrefix(strings.ToLower(os.Getenv(k)), "pt") {
			return "pt"
		}
	}
	return "en"
}

func T(key string) string {
	pack := en
	if Lang() == "pt" {
		pack = pt
	}
	if s, ok := pack[key]; ok {
		return s
	}
	return en[key]
}

